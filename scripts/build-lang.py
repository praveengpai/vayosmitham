#!/usr/bin/env python3
"""Build public/app/lang/<code>.js language packs from translation JSON files.

Usage: python3 scripts/build-lang.py <dir-with-json>
Expects in that folder: lang-<code>.json ({ui, clinical, notice, layers, deciders}) for ta/kn/te/hi/mr,
lang-ml.json ({ui}) for Malayalam, and optionally lang-extra.json ({<code>: {english: text}}).
Edit the generated packs directly for small wording fixes; re-run only when regenerating from JSON.
"""
import json, os, sys

src = sys.argv[1]
out = os.path.join(os.path.dirname(__file__), '..', 'public', 'app', 'lang')
os.makedirs(out, exist_ok=True)
extra = {}
p = os.path.join(src, 'lang-extra.json')
if os.path.exists(p):
    extra = json.load(open(p, encoding='utf-8'))

NOTE = {
    'ml': 'Malayalam', 'ta': 'Tamil', 'kn': 'Kannada', 'te': 'Telugu', 'hi': 'Hindi', 'mr': 'Marathi',
}
for code, name in NOTE.items():
    f = os.path.join(src, f'lang-{code}.json')
    if not os.path.exists(f):
        print('skip', code); continue
    d = json.load(open(f, encoding='utf-8'))
    pack = {'ui': {**d.get('ui', {}), **extra.get(code, {})}, 'clinical': d.get('clinical', {})}
    for k in ('notice', 'layers', 'deciders'):
        if k in d: pack[k] = d[k]
    pack['ui'] = {k: v for k, v in pack['ui'].items() if v}
    body = json.dumps(pack, ensure_ascii=False, indent=1)
    head = (f'// {name} language pack for Vayosmitham. Generated by scripts/build-lang.py from reviewed translations.\n'
            f'// The privacy notice ("notice") is a translation of the approved English notice; the English text prevails.\n')
    open(os.path.join(out, f'{code}.js'), 'w', encoding='utf-8').write(head + 'export default ' + body + ';\n')
    print(code, len(pack['ui']), 'ui', len(pack['clinical']), 'clinical', 'notice' if 'notice' in pack else '')
